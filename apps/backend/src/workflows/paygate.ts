import type { MedusaContainer } from "@medusajs/framework/types"
import { BigNumber, ContainerRegistrationKeys, Modules } from "@medusajs/framework/utils"
import { createStep, createWorkflow, StepResponse, WorkflowResponse } from "@medusajs/framework/workflows-sdk"
import { processPaymentWorkflow } from "@medusajs/medusa/core-flows"
import { CallbackData, CallbackToken, coinId } from "paygate-to"
import { createPaygateClient } from "../lib/paygate-client"
import { getPaygateConfig, isPaygate, paygateError } from "../lib/paygate-config"
import { decimal, findPaygateCapture, paygateReceipt, paygateTransaction, readPaygate, sealPaygate } from "../lib/paygate-state"
import { validateResearchProfile } from "../lib/research-profile"

type PrepareInput = { payment_collection_id: string; customer_id?: string; data?: unknown }
export async function preparePaygate(input: PrepareInput, container: MedusaContainer) {
  if (input.data && (typeof input.data !== "object" || Array.isArray(input.data) || Object.keys(input.data).length)) paygateError("PayGate session state is generated by the server. Do not submit payment data.")
  const query = container.resolve(ContainerRegistrationKeys.QUERY)
  const { data } = await query.graph({ entity: "cart_payment_collection", fields: ["cart.id", "cart.email", "cart.customer_id", "cart.metadata", "cart.completed_at"], filters: { payment_collection_id: input.payment_collection_id } })
  const cart = data[0]?.cart
  if (!cart || cart.completed_at || !cart.email) paygateError("This checkout is no longer available.")
  validateResearchProfile(cart, input.customer_id)
  return { cart_id: cart.id, email: cart.email }
}

const preparePaygateStep = createStep("prepare-paygate", async (input: PrepareInput, { container }) => new StepResponse(await preparePaygate(input, container)))
export const preparePaygateWorkflow = createWorkflow("prepare-paygate", function (input: PrepareInput) {
  return new WorkflowResponse(preparePaygateStep(input))
})

type CallbackInput = { originalUrl: string; headers: Record<string, string | string[] | undefined> }
export async function reconcilePaygate(input: CallbackInput, container: MedusaContainer) {
  const config = getPaygateConfig()
  if (!config.enabled) paygateError("PayGate is disabled.")
  const client = createPaygateClient(config)
  if (!(await client.callbacks.verifyRequest(config.callbackUrl, input)).valid) paygateError("Invalid PayGate callback signature.")
  const notice = CallbackData.fromRequest(input)
  const sessionId = notice.get("session")
  const reference = notice.get("reference")
  if (!sessionId || !reference || !new CallbackToken(config.secret).verify(reference, notice.get("token"))) paygateError("Invalid PayGate callback reference.")
  return container.resolve(Modules.LOCKING).execute(`paygate:${sessionId}`, async signal => {
    const payments = container.resolve(Modules.PAYMENT)
    const session = await payments.retrievePaymentSession(sessionId)
    if (!isPaygate(session.provider_id)) paygateError("The payment session is not a PayGate checkout.")
    const state = readPaygate(session.data, config.secret)
    if (state.session_id !== session.id || state.reference !== reference || state.canceled) paygateError("This PayGate checkout is no longer active.")
    if (!decimal(state.amount).eq(new BigNumber(session.amount).bigNumber!) || state.currency.toLowerCase() !== session.currency_code.toLowerCase()) paygateError("The invoice no longer matches this PayGate payment.")
    if (notice.pending) return { state: "pending" }
    if (!state.receipts.some(receipt => receipt.transaction === paygateTransaction(notice.txidIn || "") && receipt.coin === coinId(notice.coin || ""))) {
      if (!notice.coin || state.receipts.length >= 100) paygateError("This settlement requires manual review.")
      const info = await client.crypto.info(notice.coin)
      if (!notice.valueCoin || decimal(notice.valueCoin).lt(decimal(info.minimum))) paygateError("Payment is below this coin's network minimum.")
      const price = info.prices.usd ?? info.prices.USD
      if (!price || !decimal(price).gt(0)) paygateError("The settlement coin cannot be valued. Manual review is required.")
      state.receipts.push(paygateReceipt(state, notice, price))
    }
    const received = state.receipts.reduce((sum, receipt) => sum.plus(decimal(receipt.usd)), decimal("0"))
    state.settled = received.gte(decimal(state.expected_usd).times(state.min_net_ratio))
    state.review = state.settled ? "" : "underpaid"
    if (signal?.aborted) paygateError("Payment reconciliation lost its lock. Retry the callback.")
    await payments.updatePaymentSession({ id: session.id, amount: session.amount, currency_code: session.currency_code, data: { paygate: sealPaygate(state, config.secret) }, status: session.status })
    if (!state.settled) return { state: "underpaid" }
    const nativePayments = await payments.listPayments({ payment_session_id: session.id }, { relations: ["captures", "refunds", "payment_session"] })
    if (findPaygateCapture(state, nativePayments)) return { state: "paid" }
    const query = container.resolve(ContainerRegistrationKeys.QUERY)
    const { data: orders } = await query.graph({ entity: "order_cart", fields: ["order.id", "order.status"], filters: { cart_id: state.cart_id } })
    if (!orders[0]?.order || orders[0].order.status === "canceled") paygateError("The paid checkout needs order review. No payment was captured in Medusa.")
    if (signal?.aborted) paygateError("Payment reconciliation lost its lock. Retry the callback.")
    await processPaymentWorkflow(container).run({ input: { action: "captured", data: { session_id: session.id, amount: session.amount } } })
    return { state: "paid" }
  }, { timeout: 30, expire: 120 })
}

const reconcilePaygateStep = createStep("reconcile-paygate", async (input: CallbackInput, { container }) => new StepResponse(await reconcilePaygate(input, container)))
export const reconcilePaygateWorkflow = createWorkflow("reconcile-paygate", function (input: CallbackInput) {
  return new WorkflowResponse(reconcilePaygateStep(input))
})

export async function guardPaygateFulfillment(input: { order_id: string }, container: MedusaContainer) {
  const query = container.resolve(ContainerRegistrationKeys.QUERY)
  const { data } = await query.graph({ entity: "order", fields: ["id", "payment_collections.payment_sessions.id", "payment_collections.payment_sessions.provider_id", "payment_collections.payment_sessions.status"], filters: { id: input.order_id } })
  for (const collection of data[0]?.payment_collections ?? []) {
    for (const reference of collection?.payment_sessions ?? []) {
      if (!reference || !isPaygate(reference.provider_id)) continue
      const session = await container.resolve(Modules.PAYMENT).retrievePaymentSession(reference.id)
      const state = readPaygate(session.data, getPaygateConfig().secret)
      const payments = await container.resolve(Modules.PAYMENT).listPayments({ payment_session_id: session.id }, { relations: ["captures", "refunds", "payment_session"] })
      const capture = findPaygateCapture(state, payments)
      if (!capture || capture.refunds?.some(refund => new BigNumber(refund.amount).bigNumber!.gt(0)) || state.session_id !== session.id || !decimal(state.amount).eq(new BigNumber(session.amount).bigNumber!) || state.currency.toLowerCase() !== session.currency_code.toLowerCase() || !state.settled || state.canceled || state.review) paygateError("PayGate payment is awaiting verified settlement. Fulfillment and shipping are on hold.")
    }
  }
  return { allowed: true }
}
const guardPaygateFulfillmentStep = createStep("guard-paygate-fulfillment", async (input: { order_id: string }, { container }) => new StepResponse(await guardPaygateFulfillment(input, container)))
export const guardPaygateFulfillmentWorkflow = createWorkflow("guard-paygate-fulfillment", function (input: { order_id: string }) {
  return new WorkflowResponse(guardPaygateFulfillmentStep(input))
})
