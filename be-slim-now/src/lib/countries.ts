/** Italy, San Marino and the Vatican keep the leading 0 after the country code; everyone else drops it. */
const KEEPS_ZERO = new Set(["39", "378"])

/**
 * A phone number as "+<code> <number>": "+44 07700 900123" becomes "+44 7700 900123" (the 0 is only
 * dialled at home), and a number typed as "0049…" becomes "+49…".
 */
export function internationalPhone(value: string): string {
  const phone = value.trim().replace(/^00/, "+")
  const match = /^\+(\d+) 0(?=\d)/.exec(phone)
  return match && !KEEPS_ZERO.has(match[1]) ? phone.replace(/^(\+\d+) 0/, "$1 ") : phone
}
